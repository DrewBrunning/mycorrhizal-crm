// Package notices assembles the third-party attribution document for the
// artifacts this project distributes (issue #1880).
package notices

import (
	"crypto/sha256"
	"fmt"
	"sort"
	"strings"
)

// Dependency is one third-party package with the license text that must travel
// with it when the artifact is distributed.
type Dependency struct {
	Ecosystem string
	Name      string
	Version   string
	License   string
	Source    string
	Text      string
}

type licenseText struct {
	hash  string
	label string
	text  string
	used  []string
}

// Render produces the deterministic notice document for deps. Packages are
// sorted, and identical license texts are emitted once, with every package that
// uses them listed alongside.
func Render(deps []Dependency) string {
	sorted := append([]Dependency(nil), deps...)
	sort.Slice(sorted, func(i, j int) bool {
		if sorted[i].Ecosystem != sorted[j].Ecosystem {
			return sorted[i].Ecosystem < sorted[j].Ecosystem
		}
		if sorted[i].Name != sorted[j].Name {
			return sorted[i].Name < sorted[j].Name
		}
		return sorted[i].Version < sorted[j].Version
	})

	var texts []*licenseText
	byHash := map[string]*licenseText{}
	for i := range sorted {
		dep := &sorted[i]
		text := normalizeText(dep.Text)
		sum := fmt.Sprintf("%x", sha256.Sum256([]byte(text)))
		entry := byHash[sum]
		if entry == nil {
			entry = &licenseText{hash: sum, label: dep.License, text: text}
			byHash[sum] = entry
			texts = append(texts, entry)
		}
		entry.used = append(entry.used, dep.Name)
	}

	sort.SliceStable(texts, func(i, j int) bool {
		left, right := texts[i].used[0], texts[j].used[0]
		if left != right {
			return left < right
		}
		return texts[i].hash < texts[j].hash
	})

	var b strings.Builder
	b.WriteString("# Third-Party Notices\n\n")
	b.WriteString("Mycorrhizal CRM distributes the following third-party software in its all-in-one\n")
	b.WriteString("container image and in the Go server embedded in the Android app. Each entry\n")
	b.WriteString("records the package, its version, the declared license, its source, and the\n")
	b.WriteString("license text that must accompany a distribution. The Go standard library is\n")
	b.WriteString("included as one entry for the toolchain pinned by backend/go.mod.\n\n")
	b.WriteString("This file is generated by `cd backend && go run ./cmd/gennotices`. Do not edit it\n")
	b.WriteString("by hand: change a dependency, then regenerate and commit the diff. The required\n")
	b.WriteString("`Docs & security-doc citations` check in `.github/workflows/unit-tests.yml`\n")
	b.WriteString("fails when the committed file is stale (issue #1944).\n\n")
	b.WriteString("The Android APK/AAB embeds this Go server (including the Go standard library)\n")
	b.WriteString("and the IBM Plex fonts. This file and THIRD_PARTY_SOURCES.md are packaged into\n")
	b.WriteString("the app and shown under Settings > About > Third-party licenses; the Gradle\n")
	b.WriteString("dependency graph is attributed separately by AboutLibraries. npm packages are\n")
	b.WriteString("web-only and are not part of the APK/AAB.\n\n")
	b.WriteString("Bundled content assets (fonts, icons) and their full license texts are in\n")
	b.WriteString("THIRD_PARTY_SOURCES.md, shipped in the container at\n")
	b.WriteString("/app/THIRD_PARTY_SOURCES.md and served at /third-party-sources.txt.\n\n")

	writeSection := func(ecosystem, heading, sourceLabel string) {
		wrote := false
		for _, dep := range sorted {
			if dep.Ecosystem != ecosystem {
				continue
			}
			if !wrote {
				fmt.Fprintf(&b, "## %s\n\n", heading)
				fmt.Fprintf(&b, "| Package | Version | License | %s |\n", sourceLabel)
				b.WriteString("|---|---|---|---|\n")
				wrote = true
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s |\n", dep.Name, dep.Version, dep.License, dep.Source)
		}
		if wrote {
			b.WriteString("\n")
		}
	}

	writeSection("go", "Go modules", "Source")
	writeSection("npm", "npm packages", "Source")

	b.WriteString("## License texts\n\n")
	for i, entry := range texts {
		if i > 0 {
			b.WriteString("---\n\n")
		}
		users := uniqueStrings(entry.used)
		fmt.Fprintf(&b, "### %d. %s\n\n", i+1, entry.label)
		fmt.Fprintf(&b, "Applies to: %s\n\n", strings.Join(wrapCode(users), ", "))
		b.WriteString("```text\n")
		b.WriteString(entry.text)
		if !strings.HasSuffix(entry.text, "\n") {
			b.WriteString("\n")
		}
		b.WriteString("```\n\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// DetectLicenses labels a license text by its well-known opening clauses. It is
// used only for display; the full text is what carries the attribution.
func DetectLicenses(text string) []string {
	lower := strings.ToLower(text)
	type signature struct {
		name string
		all  []string
	}
	signatures := []signature{
		{"Apache-2.0", []string{"apache license", "version 2.0"}},
		{"MPL-2.0", []string{"mozilla public license version 2.0"}},
		{"MIT", []string{"permission is hereby granted, free of charge"}},
		{"ISC", []string{"permission to use, copy, modify, and/or distribute this software"}},
		{"BSD-3-Clause", []string{"redistributions of source code", "neither the name of"}},
		{"BSD-2-Clause", []string{"redistributions of source code"}},
		{"Zlib", []string{"this software is provided 'as-is'"}},
		{"GPL-2.0-or-later", []string{"gnu general public license", "version 2"}},
		{"GPL-3.0-or-later", []string{"gnu general public license", "version 3"}},
		{"AGPL-3.0-or-later", []string{"gnu affero general public license", "version 3"}},
	}
	var found []string
	for _, signature := range signatures {
		matches := true
		for _, needle := range signature.all {
			if !strings.Contains(lower, needle) {
				matches = false
				break
			}
		}
		if !matches {
			continue
		}
		if signature.name == "BSD-2-Clause" && contains(found, "BSD-3-Clause") {
			continue
		}
		found = append(found, signature.name)
	}
	if len(found) == 0 {
		return nil
	}
	return found
}

func contains(values []string, want string) bool {
	for _, value := range values {
		if value == want {
			return true
		}
	}
	return false
}

func normalizeText(text string) string {
	text = strings.ReplaceAll(text, "\r\n", "\n")
	text = strings.ReplaceAll(text, "\r", "\n")
	return strings.TrimSpace(text)
}

func uniqueStrings(values []string) []string {
	sort.Strings(values)
	out := values[:0]
	for _, value := range values {
		if len(out) == 0 || out[len(out)-1] != value {
			out = append(out, value)
		}
	}
	return out
}

func wrapCode(names []string) []string {
	wrapped := make([]string, len(names))
	for i, name := range names {
		wrapped[i] = "`" + name + "`"
	}
	return wrapped
}
