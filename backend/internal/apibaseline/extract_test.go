// ref builds a $ref SchemaRef for synthetic specs.
func ref(name string) *openapi3.SchemaRef {
	return &openapi3.SchemaRef{Ref: "#/components/schemas/" + name}
}

func sch(t *testing.T, s *openapi3.Schema) *openapi3.SchemaRef {
	t.Helper()
	return &openapi3.SchemaRef{Value: s}
}

func strType(v string) *openapi3.Types {
	return &openapi3.Types{v}
}

// TestSchemaPropertiesComposition pins that schemaProperties folds composed
// members (allOf/oneOf/anyOf) into a union of their properties, marks a
// property required when any member requires it, and sorts deterministically.
func TestSchemaPropertiesComposition(t *testing.T) {
	base := &openapi3.Schema{
		Type:     newTypes("object"),
		Required: []string{"id"},
		Properties: openapi3.Schemas{
			"id": sch(t, &openapi3.Schema{Type: strType("integer")}),
		},
	}
	ext := &openapi3.Schema{
		Type:     newTypes("object"),
		Required: []string{"name"},
		Properties: openapi3.Schemas{
			"name":  sch(t, &openapi3.Schema{Type: strType("string")}),
			"extra": ref("SomethingElse"),
		},
	}
	composed := &openapi3.Schema{
		AllOf: openapi3.SchemaRefs{sch(t, base), sch(t, ext)},
	}

	props := schemaProperties(composed)
	assert.Len(t, props, 3)

	byName := map[string]PropertySurface{}
	for _, p := range props {
		byName[p.Name] = p
	}
	assert.True(t, byName["id"].Required, "id is required by the base member")
	assert.True(t, byName["name"].Required, "name is required by the ext member")
	assert.False(t, byName["extra"].Required, "extra is not required by either member")
	assert.Equal(t, "ref:SomethingElse", byName["extra"].Type)
	assert.Equal(t, "integer", byName["id"].Type)
}

// TestSchemaPropertiesOneOfAnyOf pins the oneOf/anyOf fold path and that a
// property's enum is captured.
func TestSchemaPropertiesOneOfAnyOf(t *testing.T) {
	member := &openapi3.Schema{
		Type: newTypes("object"),
		Properties: openapi3.Schemas{
			"kind": sch(t, &openapi3.Schema{Type: strType("string"), Enum: []any{"a", "b"}}),
		},
	}
	anyOf := &openapi3.Schema{AnyOf: openapi3.SchemaRefs{sch(t, member)}}

	props := schemaProperties(anyOf)
	require.Len(t, props, 1)
	assert.Equal(t, "kind", props[0].Name)
	assert.Equal(t, []any{"a", "b"}, props[0].Enum)
}

