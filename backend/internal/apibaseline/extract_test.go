// TestCheckSupersetEnumNarrowingOnField pins the per-field enum shrink check
// (distinct from the schema-level enum check).
func TestCheckSupersetEnumNarrowingOnField(t *testing.T) {
	base := &Baseline{
		Version: BaselineVersion,
		Schemas: []SchemaSurface{{
			Name: "Thing",
			Properties: []PropertySurface{{
				Name: "kind", Type: "string", Enum: []any{"a", "b"},
			}},
		}},
	}
	cur := &Baseline{
		Version: BaselineVersion,
		Schemas: []SchemaSurface{{
			Name: "Thing",
			Properties: []PropertySurface{{
				Name: "kind", Type: "string", Enum: []any{"a"},
			}},
		}},
	}
	msgs := CheckSuperset(base, cur)
	assert.Contains(t, msgs, "enum value b on field Thing.kind was removed")
}

