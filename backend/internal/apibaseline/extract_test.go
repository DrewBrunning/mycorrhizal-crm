// TestTypeSignature pins the inline type-signature forms the drift test relies
// on for non-ref request/response bodies: primitives, arrays, objects, and
// composed forms.
func TestTypeSignature(t *testing.T) {
	cases := []struct {
		name string
		s    *openapi3.Schema
		want string
	}{
		{"nil", nil, ""},
		{"object with properties", &openapi3.Schema{Properties: openapi3.Schemas{"a": sch(t, &openapi3.Schema{Type: strType("string")})}}, "object"},
		{"array", &openapi3.Schema{Type: strType("array"), Items: sch(t, &openapi3.Schema{Type: strType("string")})}, "array<string>"},
		{"primitive", &openapi3.Schema{Type: strType("string")}, "string"},
		{"enum without type", &openapi3.Schema{Enum: []any{"a"}}, "enum"},
		{"anyOf", &openapi3.Schema{AnyOf: openapi3.SchemaRefs{sch(t, &openapi3.Schema{Type: strType("string")}), sch(t, &openapi3.Schema{Type: strType("null")})}}, "composed[null,string]"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			assert.Equal(t, tc.want, typeSignature(tc.s))
		})
	}
}

// TestSchemaKey pins ref-key vs inline-signature resolution for bodies.
func TestSchemaKey(t *testing.T) {
	assert.Equal(t, "ref:Contact", schemaKey(ref("Contact")))
	assert.Equal(t, "ref:https://example.com/ext.json", schemaKey(&openapi3.SchemaRef{Ref: "https://example.com/ext.json"}))
	assert.Equal(t, "", schemaKey(nil))
	assert.Equal(t, "string", schemaKey(sch(t, &openapi3.Schema{Type: strType("string")})))
}

// TestLoadRejectsBrokenSpec pins the two Load error paths: a missing file and
// a syntactically broken document.
func TestLoadRejectsBrokenSpec(t *testing.T) {
	t.Run("missing file", func(t *testing.T) {
		_, err := Load("/nonexistent/openapi.yaml")
		require.Error(t, err)
	})

	t.Run("invalid document", func(t *testing.T) {
		dir := t.TempDir()
		path := filepath.Join(dir, "invalid.yaml")
		// Valid YAML but not a valid OpenAPI 3.0 document (no `openapi`/
		// `info`/`paths`) — LoadFromFile parses it, doc.Validate rejects it.
		require.NoError(t, os.WriteFile(path, []byte("some: [valid, yaml]\nbut: not-openapi\n"), 0o600))
		_, err := Load(path)
		require.Error(t, err)
	})
}

// TestParseRejectsWrongVersion pins that a baseline generated by a different
// format version is rejected with a regeneration hint, rather than silently
// compared.
func TestParseRejectsWrongVersion(t *testing.T) {
	_, err := Parse([]byte(`{"version": 99}`))
	require.Error(t, err)
	assert.Contains(t, err.Error(), "regenerate")
}

