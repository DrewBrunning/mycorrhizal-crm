package prepr

// Command is one executable step (or a reminder when Reminder is set).
// Exactly one of Argv and Shell is set for an executable step. Argv is used
// wherever git-derived file names could appear, so a path is never
// interpolated into a shell; Shell is reserved for commands that genuinely
// need a pipeline (the coverage-package filter).
type Command struct {
	Label    string
	Dir      string // repo-relative working directory; "" is the repo root
	Argv     []string
	Shell    string
	Env      []string
	Repeat   int
	Warn     bool // a failure is reported but does not fail the gate
	Reminder string
}

// Area is the local pre-PR plan for one .github/filters.yaml filter.
//
// Fast is the lint/build subset (the same class as the pre-commit hook).
// Focused is the test/coverage/ratchet work: the checks that catch failing
// suites, low changed-line coverage, and per-file coverage regressions without
// the exhaustive flake-stress pass. Full is anything only the exhaustive local
// gate needs (currently nothing; flake stress is generated by the plan).
// Fix runs only with --fix, before Fast, to write formatting/lint fixes.
// Focused mode runs Fast + Focused; Full mode runs Fast + Focused + Full.
type Area struct {
	Name    string
	Note    string   // shown when the area is selected but cannot run locally
	Implies []string // other areas a change here requires
	Fix     []Command
	Fast    []Command
	Focused []Command
	Full    []Command
}

