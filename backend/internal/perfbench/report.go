// RenderReport builds docs/development/perf-benchmarks.md from the same
// measurements the baseline is built from. Unlike the baseline it DOES include
// wall-clock medians — clearly labelled as indicative, machine-specific
// context, not a gate.
func RenderReport(resultsByProfile map[string][]Result, profileOrder []string, findings []GrowthFinding) string {
	profiles := orderedProfiles(resultsByProfile, profileOrder)

	var b strings.Builder
	fmt.Fprintln(&b, "# Core operation benchmarks (PERF-02)")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "<!-- Generated by `go run ./cmd/perfbench` (issue #469). Do not hand-edit. -->\n\n")
	fmt.Fprintln(&b, "Measured baselines for the operations whose cost grows with data volume. The")
	fmt.Fprintln(&b, "**query count** and **result-set size** are the regression gate, committed to")
	fmt.Fprintln(&b, "`backend/internal/perfbench/testdata/baseline.json` and asserted by")
	fmt.Fprintln(&b, "`TestCoreOperationBenchmarks` (smoke, per PR) + `TestBenchmarksAtScale` (smoke+")
	fmt.Fprintln(&b, "typical+large, gated). The **median** column is wall-clock time from one")
	fmt.Fprintf(&b, "generating run on `%s/%s` — indicative only, never asserted, since it varies\n", runtime.GOOS, runtime.GOARCH)
	fmt.Fprintln(&b, "across hardware (issue #261's stated philosophy). This file is regenerated with")
	fmt.Fprintln(&b, "fresh medians on every run and is **not** drift-gated (only `baseline.json` is);")
	fmt.Fprintln(&b, "commit it when it moves. #471 turns these numbers into budgets.")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "Profiles are the PERF-01 dataset shapes (issue #468): %s. `large` and `stress`\n", strings.Join(profiles, ", "))
	fmt.Fprintln(&b, "are gated behind `MYCORRHIZAL_LARGE_TESTS=1`; `stress` is projection-only and is")
	fmt.Fprintln(&b, "never populated. Regenerate with `make gen-perf-baseline` (add `-large` for the")
	fmt.Fprintln(&b, "`large` column).")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "_Last generated: %s._\n\n", time.Now().UTC().Format("2006-01-02"))

	// --- per-operation measurement table ---
	fmt.Fprintln(&b, "## Measurements")
	fmt.Fprintln(&b)
	header := "| Operation | Kind | Profile | Contacts | Queries | Result size | Median |"
	sep := "|---|---|---|--:|--:|--:|--:|"
	fmt.Fprintln(&b, header)
	fmt.Fprintln(&b, sep)

	for _, op := range Registry() {
		for _, profile := range profiles {
			r, ok := findResult(resultsByProfile[profile], op.Name)
			if !ok {
				continue // # pragma: no cover — RenderReport is only called with a full measurement pass
			}
			kind := op.Category
			if op.Destructive {
				kind += ", 1x"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %d | %d | %d | %s |\n",
				op.Name, kind, profile, r.RowScale, r.Queries,
				r.ResultSize, humanDuration(r.MedianNanos))
		}
	}
	fmt.Fprintln(&b, "\n(Result size 0 = the operation returns a single record or is a write, not a collection.)")
	fmt.Fprintln(&b)

	// --- growth analysis ---
	fmt.Fprintln(&b, "## Cross-scale growth")
	fmt.Fprintln(&b)
	if len(findings) == 0 {
		fmt.Fprintln(&b, "_Not enough profiles measured to compare scales (need at least two)._")
		fmt.Fprintln(&b)
	} else {
		fmt.Fprintf(&b, "Query-count and result-size growth from the smallest to the largest measured\n")
		fmt.Fprintf(&b, "profile, against the row-count growth. The **Class** column (query count, plus\n")
		fmt.Fprintf(&b, "result size for the pairwise operations) is the deterministic gate: `superlinear`\n")
		fmt.Fprintf(&b, "there is a hard finding. **Median x** is advisory — wall-clock, not asserted —\n")
		fmt.Fprintf(&b, "and a ⏱ marks where it grew faster than the square of the row-count ratio.\n\n")
		fmt.Fprintf(&b, "Note: the PERF-01 profiles deliberately scale graph density (hubs, fan-out,\n")
		fmt.Fprintf(&b, "chain depth) faster than contact count, so a graph traversal's result size and\n")
		fmt.Fprintf(&b, "wall-clock legitimately grow faster than 3x between `smoke` and `typical` — its\n")
		fmt.Fprintf(&b, "*query count* staying flat is the property under test.\n\n")
		fmt.Fprintln(&b, "| Operation | Scales | Row x | Query x | Result x | Median x | Class | Expected |")
		fmt.Fprintln(&b, "|---|---|--:|--:|--:|--:|---|---|")
		sorted := append([]GrowthFinding(nil), findings...)
		sort.Slice(sorted, func(i, j int) bool { return sorted[i].Operation < sorted[j].Operation })
		for _, f := range sorted {
			flag := ""
			if f.Regression {
				flag = " ⚠️ regression"
			}
			median := fmt.Sprintf("%.2f", f.DurationRatio)
			if f.DurationConcern {
				median += " ⏱"
			}
			fmt.Fprintf(&b, "| `%s` | %s→%s | %.2f | %.2f | %.2f | %s | %s%s | %s |\n",
				f.Operation, f.SmallProfile, f.LargeProfile,
				f.RowScaleRatio, f.QueryRatio, f.ResultRatio, median,
				f.Class, flag, f.Expected)
		}
		fmt.Fprintln(&b)

		var superlinear, slowGrowth []string
		for _, f := range sorted {
			if f.Class == GrowthSuperlinear {
				superlinear = append(superlinear, f.Operation)
			}
			if f.DurationConcern {
				slowGrowth = append(slowGrowth, f.Operation)
			}
		}
		if len(superlinear) > 0 {
			fmt.Fprintf(&b, "**Super-linear operations (hard findings):** %s. Recorded, not necessarily\n", strings.Join(backticked(superlinear), ", "))
			fmt.Fprintln(&b, "bugs — #471 decides whether each needs a budget or a fix.")
			fmt.Fprintln(&b)
		}
		if len(slowGrowth) > 0 {
			fmt.Fprintf(&b, "**Wall-clock grew super-linearly (advisory, ⏱):** %s. Not gated (hardware-\n", strings.Join(backticked(slowGrowth), ", "))
			fmt.Fprintln(&b, "variable), but these are the \"fast at the typical profile, slow at large\"")
			fmt.Fprintln(&b, "candidates worth a closer look under `MYCORRHIZAL_LARGE_TESTS=1`.")
			fmt.Fprintln(&b)
		}
	}

	fmt.Fprintln(&b, "## Method")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "- Real migrated schema (`database.InitDB` / `internal/dbtest` — CLAUDE.md backend trap #1);")
	fmt.Fprintln(&b, "  the FTS virtual tables, triggers and hand-written indexes all exist.")
	fmt.Fprintln(&b, "- Each operation runs on a connection wrapped in `database.QueryCounter`; the")
	fmt.Fprintln(&b, "  fixture is populated on a separate connection so the tally is the operation's own.")
	fmt.Fprintf(&b, "- Read operations: one warm-up, then the median of %d timed runs (the deep\n", readIterations)
	fmt.Fprintln(&b, "  recursive-CTE traversals and the destructive merge/delete-cascade run once — the")
	fmt.Fprintln(&b, "  query count is still deterministic, only the median loses its averaging).")
	fmt.Fprintln(&b, "  Destructive operations run against a byte copy of the populated fixture.")
	fmt.Fprintln(&b, "- The pathological manifest records (the duplicate-keyword card, the dense hub with")
	fmt.Fprintln(&b, "  its fan-out of edges, the soft-deleted/re-created pair) are present in every block")
	fmt.Fprintln(&b, "  at every scale, and the hub/pathological contacts are measured explicitly.")

	return b.String()
}

func orderedProfiles(byProfile map[string][]Result, order []string) []string {
	var out []string
	seen := map[string]bool{}
	for _, p := range order {
		if _, ok := byProfile[p]; ok && !seen[p] {
			out = append(out, p)
			seen[p] = true
		}
	}
	rest := make([]string, 0)
	for p := range byProfile {
		if !seen[p] {
			rest = append(rest, p)
		}
	}
	sort.Strings(rest)
	return append(out, rest...)
}

func findResult(rs []Result, op string) (Result, bool) {
	for _, r := range rs {
		if r.Operation == op {
			return r, true
		}
	}
	return Result{}, false
}

func humanDuration(nanos int64) string {
	d := time.Duration(nanos)
	switch {
	case d < time.Microsecond:
		return fmt.Sprintf("%dns", nanos)
	case d < time.Millisecond:
		return fmt.Sprintf("%.1fµs", float64(nanos)/1e3)
	case d < time.Second:
		return fmt.Sprintf("%.1fms", float64(nanos)/1e6)
	default:
		return fmt.Sprintf("%.2fs", float64(nanos)/1e9)
	}
}

func backticked(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = "`" + s + "`"
	}
	return out
}
