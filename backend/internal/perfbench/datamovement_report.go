// RenderDataMovementReport builds docs/development/data-movement-benchmarks.md
// (PERF-03, issue #470) from the same measurements the baseline is built from.
// Unlike the baseline it carries the environment-variable numbers — wall-clock
// duration, peak heap, peak disk — clearly labelled as indicative context, not
// a gate, plus the operator-facing free-space and write-lock tables the
// milestone asks for.
func RenderDataMovementReport(byProfile map[string][]DataMovementResult, profileOrder []string, findings []MemoryGrowthFinding) string {
	profiles := orderedDMProfiles(byProfile, profileOrder)

	var b strings.Builder
	fmt.Fprintln(&b, "# Data-movement benchmarks (PERF-03)")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "<!-- Generated by `go run ./cmd/perfbench` (issue #470). Do not hand-edit. -->\n\n")
	fmt.Fprintln(&b, "The bulk operations — import, export, FTS rebuild, backup, restore, delete")
	fmt.Fprintln(&b, "cascade, duplicate detection — where the user is *not* waiting on a millisecond")
	fmt.Fprintln(&b, "budget and the failure mode is different from PERF-02's: these run long enough to")
	fmt.Fprintln(&b, "be interrupted, to exhaust memory or disk, and to hold a write lock while every")
	fmt.Fprintln(&b, "other write queues behind them.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "**The gate** (`backend/internal/perfbench/testdata/datamovement-baseline.json`,")
	fmt.Fprintln(&b, "asserted by `TestDataMovementBenchmarks` per PR and `TestDataMovementAtScale`")
	fmt.Fprintln(&b, "under `MYCORRHIZAL_LARGE_TESTS=1`) is the **rows touched**, the **peak-memory")
	fmt.Fprintln(&b, "growth class**, and whether an operation **stalled concurrent writes past the 5s")
	fmt.Fprintln(&b, "busy_timeout**. Everything in the tables below that is a byte count or a")
	fmt.Fprintf(&b, "duration is from one run on `%s/%s` and is indicative only — it is not\n", runtime.GOOS, runtime.GOARCH)
	fmt.Fprintln(&b, "asserted and it will differ on your hardware (issue #261's stance).")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "Profiles are the PERF-01 dataset shapes (issue #468): %s. `large` is gated\n", strings.Join(profiles, ", "))
	fmt.Fprintln(&b, "behind `MYCORRHIZAL_LARGE_TESTS=1`. Regenerate with `make gen-perf-baseline`")
	fmt.Fprintln(&b, "(add `-large` for the `large` column).")
	fmt.Fprintln(&b)
	fmt.Fprintf(&b, "_Last generated: %s._\n\n", time.Now().UTC().Format("2006-01-02"))

	renderDMMeasurements(&b, byProfile, profiles)
	renderDMMemoryGrowth(&b, findings)
	renderDMFreeSpace(&b, byProfile, profiles)
	renderDMWriteLock(&b, byProfile, profiles)
	renderDMMigrationNote(&b)
	renderDMMethod(&b)

	return b.String()
}

func renderDMMeasurements(b *strings.Builder, byProfile map[string][]DataMovementResult, profiles []string) {
	fmt.Fprintln(b, "## Measurements")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "| Operation | Kind | Profile | Contacts | Rows touched | Duration | Peak heap | Peak extra disk | Output |")
	fmt.Fprintln(b, "|---|---|---|--:|--:|--:|--:|--:|--:|")
	for _, op := range DataMovementRegistry() {
		for _, profile := range profiles {
			r, ok := findDMResult(byProfile[profile], op.Name)
			if !ok {
				continue // # pragma: no cover — the report is only rendered from a full pass
			}
			s := r.Sample
			fmt.Fprintf(b, "| `%s` | %s | %s | %d | %d | %s | %s | %s | %s |\n",
				op.Name, op.Category, profile, r.RowScale, s.RowsTouched,
				humanDuration(s.DurationNanos), humanBytes(s.PeakHeapBytes),
				humanBytes(s.PeakExtraDiskBytes), humanBytes(s.OutputBytes))
		}
	}
	fmt.Fprintln(b)
	fmt.Fprintln(b, "\"Peak heap\" is the highest `runtime.MemStats.HeapAlloc` seen during the operation,")
	fmt.Fprintln(b, "above a GC'd baseline taken just before it. \"Peak extra disk\" is the largest the")
	fmt.Fprintln(b, "database file + its `-wal`/`-shm` sidecars + any output/temp files grew during the")
	fmt.Fprintln(b, "run. \"Output\" is the artifact the operation produced (an export stream discarded")
	fmt.Fprintln(b, "here, a backup file kept).")
	fmt.Fprintln(b)
}

func renderDMMemoryGrowth(b *strings.Builder, findings []MemoryGrowthFinding) {
	fmt.Fprintln(b, "## Peak-memory growth (the gate)")
	fmt.Fprintln(b)
	if len(findings) == 0 {
		fmt.Fprintln(b, "_Not enough profiles measured to compare scales (need at least two — run with `-large` / `MYCORRHIZAL_LARGE_TESTS=1`)._")
		fmt.Fprintln(b)
		return
	}
	fmt.Fprintln(b, "Peak-heap growth from the smallest to the largest measured profile, against how")
	fmt.Fprintln(b, "much the operation's own work grew (or, for duplicate detection, against the")
	fmt.Fprintln(b, "dataset — its pair count is itself quadratic in a cluster). `superlinear` here is")
	fmt.Fprintln(b, "the finding the ticket cares about most: an operation whose peak memory outgrows")
	fmt.Fprintln(b, "its input **will** be OOM-killed on a small self-hosted box. `linear` is expected")
	fmt.Fprintln(b, "for the exporters (they buffer the whole result) and is recorded, not gated.")
	fmt.Fprintln(b, "`import.vcf` is declared `superlinear` on purpose — its preview pass is O(n²) in")
	fmt.Fprintln(b, "the batch size — so the gate catches a *regression* past that, not the shape")
	fmt.Fprintln(b, "itself. #471 turns these into budgets.")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "| Operation | Scales | Contacts x | Work x | Peak heap x | Peak disk x | Duration x | Class | Expected |")
	fmt.Fprintln(b, "|---|---|--:|--:|--:|--:|--:|---|---|")
	sorted := append([]MemoryGrowthFinding(nil), findings...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Operation < sorted[j].Operation })
	for _, f := range sorted {
		flag := ""
		if f.Regression {
			flag = " ⚠️ regression"
		}
		fmt.Fprintf(b, "| `%s` | %s→%s | %.2f | %.2f | %.2f | %.2f | %.2f | %s%s | %s |\n",
			f.Operation, f.SmallProfile, f.LargeProfile, f.RowScaleRatio, f.RowsTouchedRatio,
			f.PeakHeapRatio, f.PeakDiskRatio, f.DurationRatio, f.Class, flag, f.Expected)
	}
	fmt.Fprintln(b)

	var declaredSuperlinear, regressions []string
	seen := map[string]bool{}
	for _, f := range sorted {
		if f.Expected == GrowthSuperlinear && !seen[f.Operation] {
			declaredSuperlinear = append(declaredSuperlinear, f.Operation)
			seen[f.Operation] = true
		}
		if f.Regression {
			regressions = append(regressions, f.Operation)
		}
	}
	if len(declaredSuperlinear) > 0 {
		fmt.Fprintf(b, "**Super-linear peak memory (recorded findings):** %s.\n", strings.Join(backticked(declaredSuperlinear), ", "))
		fmt.Fprintln(b, "`duplicates.find_pairs` expands O(cluster²) pairs in memory; `import.vcf` holds")
		fmt.Fprintln(b, "the whole parsed batch and runs an O(n²) within-batch duplicate scan in its")
		fmt.Fprintln(b, "preview pass. Both are capped in the product (dedup is a review surface;")
		fmt.Fprintln(b, "imports cap at `services.MaxVCFContacts`), but a large input should be chunked.")
		fmt.Fprintln(b, "The `Class` column can read below `superlinear` at the smaller profiles — the")
		fmt.Fprintln(b, "O(n²) term only dominates once the input is large; the gate compares the")
		fmt.Fprintln(b, "smallest to the LARGEST measured profile. #471 / #725 decide the budget or fix.")
		fmt.Fprintln(b)
	}
	if len(regressions) > 0 {
		fmt.Fprintf(b, "**Regressions (hard failures):** %s — measured a worse memory class than declared.\n\n", strings.Join(backticked(regressions), ", "))
	}
}

func renderDMFreeSpace(b *strings.Builder, byProfile map[string][]DataMovementResult, profiles []string) {
	fmt.Fprintln(b, "## Free-space requirements (per operation)")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "What an operator must have free *before* starting each operation. An operator at")
	fmt.Fprintln(b, "60% disk needs to know this before running a backup, not during.")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "| Operation | Extra disk needed | Measured peak extra disk (largest profile) |")
	fmt.Fprintln(b, "|---|---|--:|")
	largest := ""
	if len(profiles) > 0 {
		largest = profiles[len(profiles)-1]
	}
	for _, op := range DataMovementRegistry() {
		peak := "—"
		if r, ok := findDMResult(byProfile[largest], op.Name); ok {
			peak = humanBytes(r.Sample.PeakExtraDiskBytes)
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", op.Name, op.FreeSpaceNote, peak)
	}
	fmt.Fprintln(b)
	fmt.Fprintln(b, "Rule of thumb for the operator-facing docs: **a backup or a restore needs free")
	fmt.Fprintln(b, "space at least equal to the live database size**; photos and attachments are")
	fmt.Fprintln(b, "copied on top of that and are not counted here (the benchmark fixture is")
	fmt.Fprintln(b, "metadata-only). See `docs/operations/disaster-recovery.md` → Resource requirements.")
	fmt.Fprintln(b)
}

func renderDMWriteLock(b *strings.Builder, byProfile map[string][]DataMovementResult, profiles []string) {
	fmt.Fprintln(b, "## Write-lock hold (outage vs background task)")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "A second connection issues a one-row write every 5ms for the duration of each")
	fmt.Fprintln(b, "probed operation. The longest any of those writes had to wait is the operation's")
	fmt.Fprintln(b, "write-lock hold as a concurrent writer experiences it. A stall near 5s (the")
	fmt.Fprintln(b, "`busy_timeout`) with **stalled-out = yes** means every other write failed for the")
	fmt.Fprintln(b, "operation's whole duration — that is an outage, not a background task.")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "| Operation | Profile | Probe writes completed | Max write stall | Stalled out (>5s) |")
	fmt.Fprintln(b, "|---|---|--:|--:|:-:|")
	for _, op := range DataMovementRegistry() {
		if !op.Probe {
			continue
		}
		for _, profile := range profiles {
			r, ok := findDMResult(byProfile[profile], op.Name)
			if !ok {
				continue // # pragma: no cover — full pass only
			}
			s := r.Sample
			stalled := "no"
			if s.ProbeStalledOut {
				stalled = "**yes**"
			}
			fmt.Fprintf(b, "| `%s` | %s | %d | %s | %s |\n",
				op.Name, profile, s.ProbeWrites, humanDuration(s.ProbeMaxStallNanos), stalled)
		}
	}
	fmt.Fprintln(b)
	fmt.Fprintln(b, "`fts.rebuild` holds the write lock for its whole single transaction by design")
	fmt.Fprintln(b, "(`docs/operations/search-index.md`); `backup.vacuum_into` reads through the WAL and")
	fmt.Fprintln(b, "should *not* stall writers; `import.vcf` and `delete_cascade.hub` hold it for the")
	fmt.Fprintln(b, "length of their one persistence / cascade transaction.")
	fmt.Fprintln(b)
}

