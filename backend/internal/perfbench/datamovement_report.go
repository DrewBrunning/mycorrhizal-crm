// --- small helpers -----------------------------------------------------

func orderedDMProfiles(byProfile map[string][]DataMovementResult, order []string) []string {
	var out []string
	seen := map[string]bool{}
	for _, p := range order {
		if _, ok := byProfile[p]; ok && !seen[p] {
			out = append(out, p)
			seen[p] = true
		}
	}
	rest := make([]string, 0)
	for p := range byProfile {
		if !seen[p] {
			rest = append(rest, p)
		}
	}
	sort.Strings(rest)
	return append(out, rest...)
}

func findDMResult(rs []DataMovementResult, op string) (DataMovementResult, bool) {
	for _, r := range rs {
		if r.Operation == op {
			return r, true
		}
	}
	return DataMovementResult{}, false
}

// humanBytes renders a byte count as a compact power-of-two size.
func humanBytes(n int64) string {
	if n < 0 {
		n = 0
	}
	const unit = 1024
	if n < unit {
		return fmt.Sprintf("%dB", n)
	}
	div, exp := int64(unit), 0
	for x := n / unit; x >= unit; x /= unit {
		div *= unit
		exp++
	}
	return fmt.Sprintf("%.1f%ciB", float64(n)/float64(div), "KMGT"[exp])
}
