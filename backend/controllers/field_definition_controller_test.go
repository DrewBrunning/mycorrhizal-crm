// --- Ownership scoping ---

func TestFieldDefinitionOwnershipScoping(t *testing.T) {
	db, router := setupRouter()
	router.GET("/field-definitions", ListFieldDefinitions)
	router.GET("/field-definitions/:id", GetFieldDefinition)
	router.PUT("/field-definitions/:id", withValidated(func() any { return &models.FieldDefinitionInput{} }), UpdateFieldDefinition)
	router.DELETE("/field-definitions/:id", DeleteFieldDefinition)

	var user models.User
	db.First(&user)
	otherUser := models.User{Username: "other", Password: "password123", Email: "other@example.com"}
	require.NoError(t, db.Create(&otherUser).Error)

	otherDef := createTestDefinition(t, db, otherUser.ID, "not_yours")
	require.NoError(t, db.Create(&otherDef).Error)

	// List must not include the other user's definition.
	listReq, _ := http.NewRequest("GET", "/field-definitions", nil)
	listW := httptest.NewRecorder()
	router.ServeHTTP(listW, listReq)
	var listBody struct {
		FieldDefinitions []models.FieldDefinition `json:"field_definitions"`
	}
	require.NoError(t, json.Unmarshal(listW.Body.Bytes(), &listBody))
	assert.Len(t, listBody.FieldDefinitions, 0)

	// Get/update/delete of a cross-user definition are all 404.
	for _, m := range []struct {
		method string
		body   any
	}{
		{"GET", nil},
		{"PUT", models.FieldDefinitionInput{Label: "x", Key: "y", Type: models.FieldTypeString}},
		{"DELETE", nil},
	} {
		var buf bytes.Buffer
		if m.body != nil {
			b, _ := json.Marshal(m.body)
			buf.Write(b)
		}
		req, _ := http.NewRequest(m.method, "/field-definitions/"+otherDef.ID, &buf)
		req.Header.Set("Content-Type", "application/json")
		w := httptest.NewRecorder()
		router.ServeHTTP(w, req)
		assert.Equal(t, http.StatusNotFound, w.Code, "%s on cross-user definition must be 404", m.method)
	}
}

