func TestUpdateFieldDefinition(t *testing.T) {
	db, router := setupRouter()
	router.PUT("/field-definitions/:id", withValidated(func() any { return &models.FieldDefinitionInput{} }), UpdateFieldDefinition)

	var user models.User
	db.First(&user)
	def := createTestDefinition(t, db, user.ID, "nickname")
	require.NoError(t, db.Create(&def).Error)

	// Upgrade the definition in place: label + type change, key stays stable.
	payload := models.FieldDefinitionInput{
		Label:       "Preferred name",
		Key:         "different_key", // must be ignored on update
		Type:        models.FieldTypeEnum,
		Constraints: models.FieldConstraints{Values: []string{"Alex", "Sam"}},
	}
	jsonValue, _ := json.Marshal(payload)
	req, _ := http.NewRequest("PUT", "/field-definitions/"+def.ID, bytes.NewBuffer(jsonValue))
	req.Header.Set("Content-Type", "application/json")
	w := httptest.NewRecorder()
	router.ServeHTTP(w, req)

	assert.Equal(t, http.StatusOK, w.Code)

	var reloaded models.FieldDefinition
	require.NoError(t, db.First(&reloaded, "id = ?", def.ID).Error)
	assert.Equal(t, "Preferred name", reloaded.Label)
	assert.Equal(t, models.FieldTypeEnum, reloaded.Type)
	assert.Equal(t, []string{"Alex", "Sam"}, reloaded.Constraints.Values)
	assert.Equal(t, "nickname", reloaded.Key, "Key is immutable on update")
}

