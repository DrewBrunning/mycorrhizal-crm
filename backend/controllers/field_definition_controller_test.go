// setupFieldValueRoutes wires the nested field-value routes onto a fresh
// router with one user, one contact, and a default string definition.
func setupFieldValueRoutes(t *testing.T) (*gorm.DB, *gin.Engine, models.User, models.Contact, models.FieldDefinition) {
	t.Helper()
	db, router := setupRouter()
	router.GET("/contacts/:id/field-values", ListContactFieldValues)
	router.PUT("/contacts/:id/field-values", withValidated(func() any { return &models.ContactFieldValuesInput{} }), ReplaceContactFieldValues)

	var user models.User
	db.First(&user)
	contact := models.Contact{UserID: user.ID, Firstname: "Alice"}
	require.NoError(t, db.Create(&contact).Error)
	def := createTestDefinition(t, db, user.ID, "nickname")
	require.NoError(t, db.Create(&def).Error)
	return db, router, user, contact, def
}

func TestReplaceContactFieldValues_RoundTrip(t *testing.T) {
	db, router, user, contact, def := setupFieldValueRoutes(t)

	payload := models.ContactFieldValuesInput{
		FieldValues: []models.FieldValueInput{
			{FieldDefinitionID: def.ID, Value: json.RawMessage(`"Al"`)},
		},
	}
	jsonValue, _ := json.Marshal(payload)
	req, _ := http.NewRequest("PUT", "/contacts/"+strconv.Itoa(int(contact.ID))+"/field-values", bytes.NewBuffer(jsonValue))
	req.Header.Set("Content-Type", "application/json")
	w := httptest.NewRecorder()
	router.ServeHTTP(w, req)

	assert.Equal(t, http.StatusOK, w.Code)

	var saved []models.FieldValue
	require.NoError(t, db.Where("entity_id = ? AND user_id = ?", contact.VCardUID, user.ID).Find(&saved).Error)
	require.Len(t, saved, 1)
	assert.Equal(t, def.ID, saved[0].FieldDefinitionID)
	assert.Equal(t, `"Al"`, string(saved[0].Value))

	// Read back through the GET endpoint.
	getReq, _ := http.NewRequest("GET", "/contacts/"+strconv.Itoa(int(contact.ID))+"/field-values", nil)
	getW := httptest.NewRecorder()
	router.ServeHTTP(getW, getReq)
	assert.Equal(t, http.StatusOK, getW.Code)
	var listBody struct {
		FieldValues []models.FieldValue `json:"field_values"`
	}
	require.NoError(t, json.Unmarshal(getW.Body.Bytes(), &listBody))
	require.Len(t, listBody.FieldValues, 1)
	assert.Equal(t, `"Al"`, string(listBody.FieldValues[0].Value))
}

