func createTestDefinition(t *testing.T, db *gorm.DB, userID uint, key string) models.FieldDefinition {
	t.Helper()
	return models.FieldDefinition{
		UserID:      userID,
		Label:       "Test " + key,
		Key:         key,
		Target:      models.FieldDefinitionTargetContact,
		Type:        models.FieldTypeString,
		Projection:  "internal-only",
		Sensitivity: models.RelationshipSensitivityNormal,
	}
}

func TestCreateFieldDefinition(t *testing.T) {
	db, router := setupRouter()
	router.POST("/field-definitions", withValidated(func() any { return &models.FieldDefinitionInput{} }), CreateFieldDefinition)

	var user models.User
	db.First(&user)

	payload := models.FieldDefinitionInput{
		Label:      "Gender identity",
		Key:        "gender_identity",
		Target:     models.FieldDefinitionTargetContact,
		Type:       models.FieldTypeString,
		Projection: "internal-only",
	}
	jsonValue, _ := json.Marshal(payload)
	req, _ := http.NewRequest("POST", "/field-definitions", bytes.NewBuffer(jsonValue))
	req.Header.Set("Content-Type", "application/json")
	w := httptest.NewRecorder()
	router.ServeHTTP(w, req)

	assert.Equal(t, http.StatusCreated, w.Code)

	var count int64
	db.Model(&models.FieldDefinition{}).Count(&count)
	assert.EqualValues(t, 1, count)

	var saved models.FieldDefinition
	require.NoError(t, db.First(&saved).Error)
	assert.Equal(t, user.ID, saved.UserID)
	assert.Equal(t, "internal-only", saved.Projection, "default projection applied when omitted")
	assert.Equal(t, "normal", saved.Sensitivity, "default sensitivity applied when omitted")
	assert.NotEmpty(t, saved.ID, "UUID generated by BeforeCreate")
}

