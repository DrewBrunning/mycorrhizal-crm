package controllers

// Handler guard matrix (issue #1497 coverage gate): every route-bound
// controller handler is invoked directly on a bare gin context in two states and
// its outcome is pinned.
//
//	A: no authenticated user in the context (a route mounted without
//	   AuthMiddleware) -- every authenticated handler must refuse with
//	   401 UNAUTHORIZED and never touch the database;
//	B: an authenticated user but no validated body, no path params and no query
//	   -- handlers must answer with their own typed 4xx envelope (missing
//	   "validation data", invalid id, missing field) or a well-formed
//	   success for handlers that take no input, never a panic or a bare error.
//
// The table value is "<status> <error code>" (code omitted for non-error
// responses), so a handler that starts skipping its guard, or swallows the
// missing-input case into a 2xx/5xx, fails here with the handler's name.

