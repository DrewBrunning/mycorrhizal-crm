func TestHandlerGuardMatrix(t *testing.T) {
	logtest.AllowWarnings(t, "guard-matrix requests intentionally trigger handler error logs")
	gin.SetMode(gin.ReleaseMode)
	isolateMycorrhizalImportSessions(t)
	handlers := guardHandlers()
	require.Len(t, guardExpect, len(handlers), "guardExpect and guardHandlers must list the same handlers")

	db := dbtest.New(t)
	user := models.User{Username: "guard-user", Password: "password123", Email: "guard@example.com"}
	require.NoError(t, db.Create(&user).Error)

	names := make([]string, 0, len(handlers))
	for n := range handlers {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, name := range names {
		want, ok := guardExpect[name]
		require.Truef(t, ok, "handler %s missing from guardExpect", name)
		for i, state := range []string{"A", "B"} {
			w := httptest.NewRecorder()
			c, _ := gin.CreateTestContext(w)
			c.Request = httptest.NewRequest(http.MethodPost, "/x", nil)
			c.Set("db", db)
			c.Set("cfg", config.Config{ProfilePhotoDir: os.TempDir()})
			if state == "B" {
				c.Set("userID", user.ID)
			}
			require.NotPanicsf(t, func() { handlers[name](c) }, "%s state %s", name, state)

			got := fmt.Sprint(w.Code)
			var env struct {
				Error struct {
					Code string `json:"code"`
				} `json:"error"`
			}
			if json.Unmarshal(w.Body.Bytes(), &env) == nil && env.Error.Code != "" {
				got += " " + env.Error.Code
			}
			assert.Equalf(t, want[i], got, "%s state %s: body %.200s", name, state, w.Body.String())
		}
	}
}
