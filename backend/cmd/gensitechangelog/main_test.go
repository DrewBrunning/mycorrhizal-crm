const sample = "# Changelog\n\n## [Unreleased]\n\n## [1.7.0] - 2026-11-27\n\n" +
	"- See the [config](docs/configuration-reference.md) and [floor](docs/upgrade-compatibility.md#what-happens-below-the-floor).\n" +
	"- An [ADR](docs/adrs/0039-x.md#amend), the [issue](https://github.com/o/r/issues/1), a [backend file](backend/main.go), [top](#unreleased).\n"

func TestPageFrontMatterAndRaw(t *testing.T) {
	out, err := page(sample)
	require.NoError(t, err)
	assert.True(t, strings.HasPrefix(out, "---\ntitle: Changelog\n"), "Jekyll needs front matter or it copies the file unrendered")
	assert.Contains(t, out, "{% raw %}")
	assert.Contains(t, out, "{% endraw %}")
	assert.Contains(t, out, "Generated by")
}

func TestPageRewritesLinks(t *testing.T) {
	out, err := page(sample)
	require.NoError(t, err)
	// docs/ pages are siblings of the generated page; the plain Jekyll build
	// does not turn .md links into page links, so they must be .html.
	assert.Contains(t, out, "](configuration-reference.html)")
	assert.Contains(t, out, "](upgrade-compatibility.html#what-happens-below-the-floor)")
	assert.Contains(t, out, "](adrs/0039-x.html#amend)")
	// Repo files outside docs/ are not on the site: point at GitHub.
	assert.Contains(t, out, "](https://github.com/DrewBrunning/mycorrhizal-crm/blob/main/backend/main.go)")
	// Absolute links and in-page anchors are untouched.
	assert.Contains(t, out, "](https://github.com/o/r/issues/1)")
	assert.Contains(t, out, "](#unreleased)")
}

func TestPageRefusesLiquidEndTag(t *testing.T) {
	_, err := page("# Changelog\n\n{% endraw %}\n")
	assert.Error(t, err, "an embedded endraw would end the Liquid escape early")
}

func TestRunWritesFile(t *testing.T) {
	dir := t.TempDir()
	in := filepath.Join(dir, "CHANGELOG.md")
	outPath := filepath.Join(dir, "changelog.md")
	require.NoError(t, os.WriteFile(in, []byte(sample), 0o644))
	var stderr bytes.Buffer
	require.Equal(t, 0, run([]string{"-in", in, "-out", outPath}, &stderr), stderr.String())
	got, err := os.ReadFile(outPath)
	require.NoError(t, err)
	assert.Contains(t, string(got), "title: Changelog")
	assert.Equal(t, 2, run([]string{"-in", filepath.Join(dir, "missing.md"), "-out", outPath}, &stderr))
}

// TestRealChangelogLinksResolve guards the real file: every link that becomes a
// sibling-page link must name a docs page that exists, so the published page
// has no dead links when a release adds one.
func TestRealChangelogLinksResolve(t *testing.T) {
	data, err := os.ReadFile("../../../CHANGELOG.md")
	require.NoError(t, err)
	out, err := page(string(data))
	require.NoError(t, err)
	link := regexp.MustCompile(`\]\(([^)\s]+)\)`)
	for _, m := range link.FindAllStringSubmatch(out, -1) {
		target := m[1]
		if strings.Contains(target, ":") || strings.HasPrefix(target, "#") {
			continue
		}
		file := strings.SplitN(target, "#", 2)[0]
		require.False(t, strings.HasSuffix(file, ".md"), "%q would 404 on the site", target)
		file = strings.TrimSuffix(file, ".html") + ".md"
		_, err := os.Stat(filepath.Join("../../../docs", file))
		assert.NoError(t, err, "link %q does not resolve under docs/", target)
	}
}
